// Writes the PowerPoint add-in's manifest (the file PowerPoint installs the add-in from).
//   node scripts/office-manifest.mjs [out.xml ...]
// The add-in's pages are served from TOYBOX_OFFICE_URL, by default this repository's
// GitHub Pages site. To host it yourself (e.g. on a university web server), build the
// demo, copy dist/ there, and run this with TOYBOX_OFFICE_URL=https://your.host/path/office/
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
let base = process.env.TOYBOX_OFFICE_URL || 'https://leepee.github.io/ToyBox/office/';
if (!base.endsWith('/')) base += '/';
const origin = new URL(base).origin;
// A fixed id: PowerPoint uses it to recognise the add-in in saved presentations.
const id = process.env.TOYBOX_OFFICE_ID || '2949f924-4654-4c6f-bcc3-32df70c2db58';
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const description =
  'Interactive toys on your slides: sliders, drawings, quizzes and simulations that work in the slide show. Make them with AI, and use the same toy in Moodle.';

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- ToyBox for PowerPoint. GENERATED by scripts/office-manifest.mjs; do not edit. -->
<OfficeApp xmlns="http://schemas.microsoft.com/office/appforoffice/1.1"
           xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
           xsi:type="ContentApp">
  <Id>${id}</Id>
  <Version>1.0.0.0</Version>
  <ProviderName>ToyBox</ProviderName>
  <DefaultLocale>en-GB</DefaultLocale>
  <DisplayName DefaultValue="ToyBox" />
  <Description DefaultValue="${esc(description)}" />
  <IconUrl DefaultValue="${base}icon-32.png" />
  <HighResolutionIconUrl DefaultValue="${base}icon-64.png" />
  <SupportUrl DefaultValue="https://github.com/Leepee/ToyBox" />
  <AppDomains>
    <AppDomain>${origin}</AppDomain>
  </AppDomains>
  <Hosts>
    <Host Name="Presentation" />
  </Hosts>
  <DefaultSettings>
    <SourceLocation DefaultValue="${base}content.html" />
    <RequestedWidth>720</RequestedWidth>
    <RequestedHeight>405</RequestedHeight>
  </DefaultSettings>
  <Permissions>ReadWriteDocument</Permissions>
  <AllowSnapshot>true</AllowSnapshot>
</OfficeApp>
`;

const outs = process.argv.slice(2).length ? process.argv.slice(2) : [resolve(root, 'office/manifest.xml')];
for (const out of outs) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, xml);
  console.log(`wrote ${out} (pages at ${base})`);
}
