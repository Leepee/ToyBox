// Builds the Moodle plugin's JavaScript and CSS from the shared TypeScript.
//
//   moodle/src/view.ts, editor.ts  ──►  moodle/toybox/amd/src/*.js     (readable ES module, for reference/review)
//                                  ──►  moodle/toybox/amd/build/*.min.js (AMD, what Moodle actually loads)
//   core/src/player.css + moodle/src/styles.css ──► moodle/toybox/styles.css
//
// Moodle's own grunt build isn't needed. Run: npm run build:moodle
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const plugin = resolve(root, 'moodle/toybox');
const entries = ['view', 'editor'];
const banner = (name) =>
  `// This file is part of the ToyBox activity for Moodle (mod_toybox). GPL v3 or later.\n` +
  `// GENERATED from moodle/src/${name}.ts and core/src by scripts/build-moodle.mjs. Do not edit by hand.\n`;
const common = {
  bundle: true,
  platform: 'browser',
  target: 'es2019',
  external: ['core/*'],
  write: false,
  logLevel: 'warning',
};

for (const name of entries) {
  const entry = resolve(root, `moodle/src/${name}.ts`);

  // Readable ES module (kept in amd/src as Moodle expects).
  const esm = await build({ ...common, entryPoints: [entry], format: 'esm' });
  writeFileSync(resolve(plugin, `amd/src/${name}.js`), banner(name) + esm.outputFiles[0].text);

  // AMD module for Moodle's RequireJS loader: define('mod_toybox/<name>', deps, factory).
  const cjs = await build({ ...common, entryPoints: [entry], format: 'cjs', minify: true });
  const code = cjs.outputFiles[0].text;
  const deps = [...new Set([...code.matchAll(/require\("(core\/[^"]+)"\)/g)].map((m) => m[1]))];
  const amd =
    `define("mod_toybox/${name}",${JSON.stringify(deps)},function(){` +
    `var __m={};${deps.map((d, i) => `__m[${JSON.stringify(d)}]=arguments[${i}];`).join('')}` +
    `var require=function(n){return __m[n]};var module={exports:{}},exports=module.exports;` +
    `${code}\nreturn module.exports;});\n`;
  writeFileSync(resolve(plugin, `amd/build/${name}.min.js`), amd);
  console.log(`mod_toybox/${name}: ${(amd.length / 1024).toFixed(1)} KB, deps: ${deps.join(', ') || 'none'}`);
}

const css =
  '/* GENERATED by scripts/build-moodle.mjs from core/src/player.css and moodle/src/styles.css. */\n\n' +
  readFileSync(resolve(root, 'core/src/player.css'), 'utf8') +
  '\n' +
  readFileSync(resolve(root, 'moodle/src/styles.css'), 'utf8');
writeFileSync(resolve(plugin, 'styles.css'), css);
console.log('styles.css written');
