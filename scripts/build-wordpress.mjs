// Builds the WordPress plugin's JavaScript and CSS from the shared TypeScript.
//   wordpress/src/view.ts   ──► wordpress/toybox/assets/view.js    (front end)
//   wordpress/src/editor.ts ──► wordpress/toybox/assets/editor.js  (Toy edit screen)
// Run: npm run build:wordpress
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'wordpress/toybox/assets');
const banner = '/* ToyBox for WordPress. GPL v3 or later. GENERATED by scripts/build-wordpress.mjs; do not edit. */';

for (const name of ['view', 'editor']) {
  await build({
    entryPoints: [resolve(root, `wordpress/src/${name}.ts`)],
    outfile: resolve(out, `${name}.js`),
    bundle: true,
    format: 'iife',
    target: 'es2019',
    minify: true,
    banner: { js: banner },
    logLevel: 'warning',
  });
  console.log(`assets/${name}.js`);
}
const css = (files) => banner + '\n' + files.map((f) => readFileSync(resolve(root, f), 'utf8')).join('\n');
writeFileSync(resolve(out, 'toybox.css'), css(['core/src/player.css', 'wordpress/src/toybox.css']));
// The editor reuses the Moodle editor's layout styles plus WordPress shims.
writeFileSync(resolve(out, 'editor.css'), css(['core/src/player.css', 'moodle/src/styles.css', 'wordpress/src/editor-admin.css']));
console.log('assets/toybox.css, assets/editor.css');
